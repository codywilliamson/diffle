// renders the keyboard docs from the keymap table, so README and the docs site never drift.
//   bun scripts/keymap-docs.ts          rewrite the README section and the docs-site snippet
//   bun scripts/keymap-docs.ts --check  exit 1 when README is out of sync
// the README section lives between the marker comments below; the docs snippet is written to
// the path in KEYMAP_DOCS_OUT, when set, for the docs-site PR to paste.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BINDINGS, CHORD_TIMEOUT_MS, helpGroups } from "../client/src/lib/keymap/keymap";

export const README_START = "<!-- keymap:start (generated by scripts/keymap-docs.ts) -->";
export const README_END = "<!-- keymap:end -->";

const INTRO = `Press \`?\` in the UI for this list at any time; it is generated from the same key table the app uses. Keys follow one grammar, vim style: an optional count, then a key or a two-key chord starting with \`g\`. \`10j\` moves ten lines. A count waits until the next key or \`Esc\`. A half-typed \`g\` chord is dropped after ${CHORD_TIMEOUT_MS / 1000} second, and so is a chord with an unknown second key, without running anything. \`Esc\` cancels a pending count or chord first, then closes the open dialog. Keys are ignored while you type in a field.`;

const CURSOR_NOTE =
  "The cursor is the highlighted row. Collapsed, binary and not-yet-loaded large files have no lines to rest on, so `j` and `k` skip them and `J` and `K` park on the file header.";

const MOVED_KEYS =
  "Keys that changed: `j` / `k` used to step files (now `J` / `K`), the scorecard moved from `g` to `gc`, feedback preview from `c` to `P`, and what's new from `n` to `gw`.";

// shortcuts that live outside the keymap table (the comment editor and the diff pane own them)
const EXTRA_ROWS: Record<string, [string, string][]> = {
  Code: [["Ctrl/⌘ + click", "Go to definition of the word under the pointer. Resting the pointer on a word shows its hover docs."]],
  Help: [["Ctrl/⌘ + Enter", "Save the open comment"]],
};

function table(rows: [string, string][]): string {
  return ["| key | action |", "| --- | --- |", ...rows.map(([k, a]) => `| \`${k}\` | ${a} |`)].join("\n");
}

export function renderKeymapDocs(headingLevel: number): string {
  const h = "#".repeat(headingLevel);
  const groups = helpGroups(BINDINGS).map(({ group, bindings }) => {
    const rows: [string, string][] = bindings.map((b) => [b.keys, b.count ? `${b.label} (takes a count)` : b.label]);
    return `${h} ${group}\n\n${table([...rows, ...(EXTRA_ROWS[group] ?? [])])}`;
  });
  return [INTRO, ...groups, CURSOR_NOTE, MOVED_KEYS].join("\n\n");
}

export function renderReadmeBlock(): string {
  return `${README_START}\n\n${renderKeymapDocs(3)}\n\n${README_END}`;
}

// README with its generated block replaced (or throws when the markers are missing).
export function syncReadme(readme: string): string {
  const start = readme.indexOf(README_START);
  const end = readme.indexOf(README_END);
  if (start === -1 || end === -1 || end < start) throw new Error("README.md is missing the keymap markers");
  return readme.slice(0, start) + renderReadmeBlock() + readme.slice(end + README_END.length);
}

if (import.meta.main) {
  const readmePath = join(import.meta.dir, "..", "README.md");
  const current = readFileSync(readmePath, "utf8");
  const next = syncReadme(current.replace(/\r\n/g, "\n"));
  if (process.argv.includes("--check")) {
    if (next !== current.replace(/\r\n/g, "\n")) {
      console.error("README.md keyboard section is out of date; run: bun scripts/keymap-docs.ts");
      process.exit(1);
    }
  } else {
    writeFileSync(readmePath, next);
    const out = process.env.KEYMAP_DOCS_OUT;
    if (!out) {
      console.log("wrote README.md");
      process.exit(0);
    }
    writeFileSync(out, `<!-- generated by scripts/keymap-docs.ts: replace the Keyboard shortcuts section of reviewing-changes.md -->\n\n## Keyboard shortcuts\n\n${renderKeymapDocs(3)}\n`);
    console.log(`wrote README.md and ${out}`);
  }
}
